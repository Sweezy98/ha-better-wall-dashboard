export const TRANSLATIONS: Record<string, Record<TranslationKey, string>> = { en, de };

export function translate(language: string, key: TranslationKey, values?: Record<string, string | number>): string {
  const table = TRANSLATIONS[language.split('-')[0]] ?? en;
  let text = table[key] ?? en[key] ?? key;
  if (values) {
    for (const [name, value] of Object.entries(values)) text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}
